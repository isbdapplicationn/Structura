import type { AppTemplate, ConditionalRuleGroup, FieldConfig } from '../types/builder.ts';

const NO_LOGIC: ConditionalRuleGroup = { enabled: false, combinator: 'AND', rules: [] };

function makeField(
  partial: Partial<Omit<FieldConfig, 'id'>> & Pick<FieldConfig, 'type' | 'label' | 'key'>
): Omit<FieldConfig, 'id'> {
  return {
    placeholder: '',
    helpText: '',
    defaultValue: partial.type === 'switch' ? false : partial.type === 'rating' ? 0 : '',
    required: false,
    colSpan: 1,
    widthPercent: 50,
    columnPosition: 'auto',
    hidden: partial.type === 'hidden',
    disabled: false,
    readOnly: partial.type === 'auto_number',
    validation: {
      emailValidation: partial.type === 'email',
    },
    visibilityLogic: NO_LOGIC,
    requiredLogic: NO_LOGIC,
    ...partial,
  };
}

