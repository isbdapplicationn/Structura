export function formatLocalizedNumber(value: number, language: LanguageCode): string {
  try {
    return new Intl.NumberFormat(language === 'bn' ? 'bn-BD' : 'en-US').format(value);
  } catch {
    return String(value);
  }
}

export function formatLocalizedDate(input: unknown, language: LanguageCode): string {
  if (!input) return '—';
  let date: Date;
  if (input instanceof Date) {
    date = input;
  } else if (typeof input === 'object' && input !== null && 'toDate' in input && typeof (input as { toDate: () => Date }).toDate === 'function') {
    date = (input as { toDate: () => Date }).toDate();
  } else if (typeof input === 'string' || typeof input === 'number') {
    date = new Date(input);
  } else {
    return '—';
  }
  if (Number.isNaN(date.getTime())) return '—';
  return new Intl.DateTimeFormat(language === 'bn' ? 'bn-BD' : 'en-US', {
    year: 'numeric',
    month: 'short',
    day: 'numeric',
  }).format(date);
}
